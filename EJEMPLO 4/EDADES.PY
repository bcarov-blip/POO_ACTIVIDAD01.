edad_juan = int(input("Ingrese la edad de Juan: "))

edad_alberto = (2 * edad_juan) // 3
edad_ana = (4 * edad_juan) // 3
edad_mama = edad_alberto + edad_juan + edad_ana


print("LAS EDADES SON:")
print("ALBERTO:", edad_alberto)
print("JUAN:", edad_juan)
print("ANA:", edad_ana)
print("MAMÁ:", edad_mama)